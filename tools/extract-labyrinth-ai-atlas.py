"""Extract the v0.11.5 image-model labyrinth atlas into runtime assets.

The source atlas is a labelled composition generated by an image model. This
script crops each asset, removes the dark atlas background, filters label/noise
components, and writes the exact canvas sizes expected by the game.

Usage:
    python tools/extract-labyrinth-ai-atlas.py \
      asset-packs/cc0-pixel-v10/sources/labyrinth-ai-v0115/labyrinth-ai-atlas.png \
      asset-packs/cc0-pixel-v10/labyrinth
"""

