#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const dist = path.resolve(process.argv[2] ?? "apps/web/dist");
const cachePrefix = process.argv[3] ?? process.env.OFFLINE_CACHE_PREFIX ?? "hero-language-camp-";
const rawBase = process.env.GITHUB_PAGES_BASE ?? process.env.BASE_URL ?? "/";
const normalizedBase = rawBase === "/" ? "/" : `/${rawBase.replace(/^\/+|\/+$/g, "")}/`;

async function walk(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === "sw.js" || entry.name.startsWith(".")) continue;
    const absolute = path.join(directory, entry.name);
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute, relative));
    else if (entry.isFile() && !relative.endsWith(".map") && !relative.endsWith(".md")) files.push(relative);
  }
  return files;
}

const isAudio = (file) => /\.(mp3|wav|m4a|ogg|aac)$/i.test(file);
const files = (await walk(dist)).sort();
const digest = createHash("sha256"); // whole release: names the app cache
const audioDigest = createHash("sha256"); // audio only: names the audio cache
const fileHash = new Map(); // per-file content hash (16 hex chars) used to adopt unchanged cache entries
for (const file of files) {
  const content = await readFile(path.join(dist, file));
  fileHash.set(file, createHash("sha256").update(content).digest("hex").slice(0, 16));
  digest.update(file);
  digest.update(content);
  if (isAudio(file)) {
    audioDigest.update(file);
    audioDigest.update(content);
  }
}
const version = digest.digest("hex").slice(0, 12);
const audioVersion = audioDigest.digest("hex").slice(0, 12);
const toUrl = (file) => `${normalizedBase}${file}`.replace(/\/{2,}/g, "/");
const essentialFiles = files.filter((file) => !isAudio(file));
const audioFiles = files.filter(isAudio);
const essentialUrls = essentialFiles.map(toUrl);
const audioUrls = audioFiles.map(toUrl);
const essentialHashes = essentialFiles.map((file) => fileHash.get(file));
const audioHashes = audioFiles.map((file) => fileHash.get(file));
const bootUrls = files.filter((file) =>
  file === "index.html"
  || file === "manifest.webmanifest"
  || /^assets\/.*\.(js|css)$/i.test(file)
  || /^icons\/.*\.png$/i.test(file)
).map(toUrl);

const script = `/* generated by tools/generate-offline-service-worker.mjs */
const VERSION = ${JSON.stringify(version)};
const AUDIO_VERSION = ${JSON.stringify(audioVersion)};
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const APP_CACHE = CACHE_PREFIX + "app-" + VERSION;
// Named from an audio-only digest: releases that do not touch audio keep the same cache.
const AUDIO_CACHE = CACHE_PREFIX + "audio-" + AUDIO_VERSION;
const APP_BASE = ${JSON.stringify(normalizedBase)};
const BOOT_URLS = ${JSON.stringify(bootUrls)};
const ESSENTIAL_URLS = ${JSON.stringify(essentialUrls)};
const AUDIO_URLS = ${JSON.stringify(audioUrls)};
// Parallel to ESSENTIAL_URLS / AUDIO_URLS: first 16 hex chars of the SHA-256 of each file.
const ESSENTIAL_HASHES = ${JSON.stringify(essentialHashes)};
const AUDIO_HASHES = ${JSON.stringify(audioHashes)};
const HASH_BY_URL = new Map();
ESSENTIAL_URLS.forEach((url, index) => HASH_BY_URL.set(url, ESSENTIAL_HASHES[index]));
AUDIO_URLS.forEach((url, index) => HASH_BY_URL.set(url, AUDIO_HASHES[index]));
const MAX_ATTEMPTS = 3;
const DOWNLOAD_CONCURRENCY = 3;
const PROGRESS_INTERVAL_MS = 250;
let activeDownload = null;

async function notifyClients(message) {
  const clientsList = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  for (const client of clientsList) client.postMessage(message);
}

function sleep(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

async function fetchWithRetry(url, attempts = MAX_ATTEMPTS) {
  let lastError;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      const response = await fetch(url, { cache: "no-cache" });
      if (!response.ok) throw new Error("HTTP " + response.status);
      return response;
    } catch (error) {
      lastError = error;
      if (attempt < attempts) await sleep(300 * attempt);
    }
  }
  throw lastError ?? new Error("Unable to download " + url);
}

async function cacheUrl(cache, url) {
  if (await cache.match(url, { ignoreSearch: false })) return false;
  const response = await fetchWithRetry(url);
  await cache.put(url, response.clone());
  return true;
}

async function getCachedUrlSet(cacheName) {
  const cache = await caches.open(cacheName);
  const keys = await cache.keys();
  return new Set(keys.map((request) => new URL(request.url).pathname));
}

async function sha256Short(buffer) {
  const digest = await crypto.subtle.digest("SHA-256", buffer);
  return Array.from(new Uint8Array(digest).slice(0, 8), (byte) => byte.toString(16).padStart(2, "0")).join("");
}

// Copy entries whose bytes are unchanged from caches of earlier releases, so a
// release only downloads files that really changed. Safe by construction: an
// entry is only adopted when its content hash equals the hash in this release.
async function adoptUnchangedEntries(cache, cacheName, urls) {
  const cached = await getCachedUrlSet(cacheName);
  const missing = urls.filter((url) => !cached.has(new URL(url, self.location.origin).pathname));
  if (missing.length === 0) return 0;
  const previousNames = (await caches.keys()).filter((name) => name.startsWith(CACHE_PREFIX) && name !== cacheName);
  if (previousNames.length === 0) return 0;
  const previous = [];
  for (const name of previousNames) previous.push(await caches.open(name));
  let adopted = 0;
  for (const url of missing) {
    const expected = HASH_BY_URL.get(url);
    if (!expected) continue;
    for (const oldCache of previous) {
      const hit = await oldCache.match(url);
      if (!hit) continue;
      try {
        const copy = hit.clone();
        if (await sha256Short(await hit.arrayBuffer()) !== expected) continue;
        await cache.put(url, copy);
        adopted += 1;
        break;
      } catch {
        // Unreadable entry: fall back to downloading it.
      }
    }
  }
  return adopted;
}

async function getGroupStatus(cacheName, urls) {
  const cached = await getCachedUrlSet(cacheName);
  const completed = urls.filter((url) => cached.has(new URL(url, self.location.origin).pathname)).length;
  return { completed, total: urls.length, failed: Math.max(0, urls.length - completed) };
}

async function getOfflineStatus() {
  const [essential, audio] = await Promise.all([
    getGroupStatus(APP_CACHE, ESSENTIAL_URLS),
    getGroupStatus(AUDIO_CACHE, AUDIO_URLS)
  ]);
  return {
    type: "OFFLINE_STATUS",
    version: VERSION,
    essential,
    audio,
    ready: essential.completed === essential.total && audio.completed === audio.total
  };
}

async function reportStatus(type = "OFFLINE_STATUS") {
  const status = await getOfflineStatus();
  await notifyClients({ ...status, type });
  if (status.ready) await cleanupOldCaches();
  return status;
}

async function downloadGroup(group, cacheName, urls) {
  const cache = await caches.open(cacheName);
  await adoptUnchangedEntries(cache, cacheName, urls).catch(() => 0);
  const cached = await getCachedUrlSet(cacheName);
  const queue = urls.filter((url) => !cached.has(new URL(url, self.location.origin).pathname));
  let completed = urls.length - queue.length;
  let nextIndex = 0;
  let lastProgressAt = 0;
  const failures = [];
  const postProgress = async (extra, force) => {
    const now = Date.now();
    if (!force && now - lastProgressAt < PROGRESS_INTERVAL_MS) return;
    lastProgressAt = now;
    await notifyClients({ type: "OFFLINE_PROGRESS", group, completed, total: urls.length, failed: failures.length, ...extra });
  };
  await postProgress({}, true);

  const workerCount = Math.min(DOWNLOAD_CONCURRENCY, Math.max(1, queue.length));
  const workers = Array.from({ length: workerCount }, async () => {
    while (nextIndex < queue.length) {
      const url = queue[nextIndex++];
      try {
        await cacheUrl(cache, url);
        completed += 1;
      } catch (error) {
        failures.push({ url, message: error instanceof Error ? error.message : String(error) });
      }
      await postProgress({ currentUrl: url }, false);
    }
  });
  await Promise.all(workers);
  await postProgress({}, true);
  return failures;
}

async function downloadEverything() {
  await reportStatus("OFFLINE_STATUS");
  const essentialFailures = await downloadGroup("essential", APP_CACHE, ESSENTIAL_URLS);
  const audioFailures = await downloadGroup("audio", AUDIO_CACHE, AUDIO_URLS);
  const status = await reportStatus("OFFLINE_COMPLETE");
  if (essentialFailures.length || audioFailures.length) {
    await notifyClients({
      type: "OFFLINE_ERRORS",
      failures: [...essentialFailures, ...audioFailures],
      essential: status.essential,
      audio: status.audio
    });
  }
  return status;
}

function startDownload() {
  if (!activeDownload) {
    activeDownload = downloadEverything().finally(() => { activeDownload = null; });
  }
  return activeDownload;
}

async function cleanupOldCaches() {
  const names = await caches.keys();
  await Promise.all(names
    .filter((name) => name.startsWith(CACHE_PREFIX) && name !== APP_CACHE && name !== AUDIO_CACHE)
    .map((name) => caches.delete(name)));
}

async function findInAnyAppCache(request) {
  const currentApp = await caches.open(APP_CACHE);
  const currentAudio = await caches.open(AUDIO_CACHE);
  const current = await currentApp.match(request) || await currentAudio.match(request);
  if (current) return current;
  const names = await caches.keys();
  for (const name of names) {
    if (!name.startsWith(CACHE_PREFIX) || name === APP_CACHE || name === AUDIO_CACHE) continue;
    const cached = await (await caches.open(name)).match(request);
    if (cached) return cached;
  }
  return undefined;
}

function parseSingleRange(rangeHeader, size) {
  const match = /^bytes=(\\d*)-(\\d*)$/.exec(rangeHeader.trim());
  if (!match || (!match[1] && !match[2])) return null;

  let start;
  let end;
  if (!match[1]) {
    const suffixLength = Number(match[2]);
    if (!Number.isFinite(suffixLength) || suffixLength <= 0) return null;
    start = Math.max(0, size - suffixLength);
    end = size - 1;
  } else {
    start = Number(match[1]);
    end = match[2] ? Number(match[2]) : size - 1;
  }

  if (!Number.isFinite(start) || !Number.isFinite(end) || start < 0 || start >= size || start > end) return null;
  return { start, end: Math.min(end, size - 1) };
}

async function createPartialResponse(request, cachedResponse) {
  const rangeHeader = request.headers.get("range");
  if (!rangeHeader) return cachedResponse;

  const body = await cachedResponse.arrayBuffer();
  const range = parseSingleRange(rangeHeader, body.byteLength);
  if (!range) {
    return new Response(null, {
      status: 416,
      headers: { "Content-Range": "bytes */" + body.byteLength }
    });
  }

  const partialBody = body.slice(range.start, range.end + 1);
  const headers = new Headers(cachedResponse.headers);
  headers.delete("Content-Encoding");
  headers.set("Accept-Ranges", "bytes");
  headers.set("Content-Range", "bytes " + range.start + "-" + range.end + "/" + body.byteLength);
  headers.set("Content-Length", String(partialBody.byteLength));

  return new Response(partialBody, {
    status: 206,
    statusText: "Partial Content",
    headers
  });
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(APP_CACHE);
    await adoptUnchangedEntries(cache, APP_CACHE, BOOT_URLS).catch(() => 0);
    const failures = [];
    for (const url of BOOT_URLS) {
      try {
        await cacheUrl(cache, url);
      } catch (error) {
        failures.push({ url, message: error instanceof Error ? error.message : String(error) });
      }
    }
    await notifyClients({ type: "OFFLINE_BOOT_READY", version: VERSION, failures });
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    await self.clients.claim();
    await reportStatus();
  })());
});

self.addEventListener("message", (event) => {
  const type = event.data?.type;
  if (type === "SKIP_WAITING") self.skipWaiting();
  if (type === "GET_OFFLINE_STATUS") event.waitUntil(reportStatus());
  if (type === "START_OFFLINE_DOWNLOAD" || type === "RETRY_OFFLINE_DOWNLOAD") event.waitUntil(startDownload());
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const requestUrl = new URL(event.request.url);
  if (requestUrl.origin !== self.location.origin || !requestUrl.pathname.startsWith(APP_BASE)) return;

  event.respondWith((async () => {
    const rangeHeader = event.request.headers.get("range");
    if (rangeHeader) {
      // Safari and other media engines request byte ranges. Cache Storage keeps
      // the full 200 response, so construct the expected 206 response from it.
      const cachedFullResponse = await findInAnyAppCache(event.request.url);
      if (cachedFullResponse) return createPartialResponse(event.request, cachedFullResponse);

      // Return network partial content directly. Cache.put() rejects 206
      // responses, and that rejection must never cancel valid playback.
      return fetch(event.request);
    }

    const cached = await findInAnyAppCache(event.request);
    if (cached) return cached;
    try {
      const response = await fetch(event.request);
      if (response.ok && response.status !== 206) {
        const cache = await caches.open(/(^|\\/)audio\\//.test(requestUrl.pathname) ? AUDIO_CACHE : APP_CACHE);
        try {
          await cache.put(event.request, response.clone());
        } catch {
          // Network delivery is more important than opportunistic caching.
        }
      }
      return response;
    } catch (error) {
      if (event.request.mode === "navigate") {
        const fallbackRequest = new Request(APP_BASE + "index.html");
        const fallback = await findInAnyAppCache(fallbackRequest);
        if (fallback) return fallback;
      }
      throw error;
    }
  })());
});
`;
await writeFile(path.join(dist, "sw.js"), script, "utf8");
console.log(`Generated resumable offline service worker ${version}: ${essentialUrls.length} essential + ${audioUrls.length} audio files at ${normalizedBase}`);
